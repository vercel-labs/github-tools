// Regenerates app/utils/figure-data/presets.ts. From packages/github-tools, after `pnpm build`:
//   node ../../apps/docs/scripts/generate-preset-figure-data.mjs > ../../apps/docs/app/utils/figure-data/presets.ts
const m = await import(process.cwd() + '/dist/index.mjs')
const names = Object.keys(m.GITHUB_TOOL_NAMES)
const writes = Object.keys(m.GITHUB_WRITE_TOOLS)
// Each group starts at this tool, in catalog order.
const starts = [
  ['Repository', 'getRepository'], ['Pull requests', 'listPullRequests'], ['Issues', 'getIssueContext'],
  ['Reactions', 'listIssueReactions'], ['Discussions', 'listDiscussions'], ['Notifications', 'listNotifications'],
  ['Search', 'searchCode'], ['Commits', 'listCommits'], ['Gists', 'listGists'], ['Actions', 'listWorkflows'],
  ['Checks', 'listCheckRuns'], ['Releases', 'listReleases'], ['Security', 'listCodeScanningAlerts'],
]
const groups = starts.map(([label, first], i) => {
  const from = names.indexOf(first)
  const to = i + 1 < starts.length ? names.indexOf(starts[i + 1][1]) : names.length
  if (from === -1 || to < from) throw new Error(`catalog order changed near ${first}`)
  return { label, tools: names.slice(from, to) }
})
const order = ['repo-explorer', 'code-review', 'issue-triage', 'ci-ops', 'security-audit', 'release-manager', 'discussion-moderator', 'notification-inbox', 'pr-author', 'maintainer']
if (order.length !== Object.keys(m.PRESET_TOOLS).length) throw new Error('preset list changed')
const list = a => a.map(t => `'${t}'`).join(', ')
let out = `// Mirrors GITHUB_TOOL_CATALOG (order and write flags) and PRESET_TOOLS from packages/github-tools/src/core.
// Generated by scripts/generate-preset-figure-data.mjs; src/docs.test.ts in the SDK fails when it drifts.

export interface ToolGroup {
  label: string
  tools: readonly string[]
}

export const TOOL_GROUPS: readonly ToolGroup[] = [
${groups.map(g => `  { label: '${g.label}', tools: [${list(g.tools)}] }`).join(',\n')}
]

export const WRITE_TOOLS: ReadonlySet<string> = new Set([
  ${list(writes)}
])

export const PRESET_TOOLS = {
${order.map(p => `  '${p}': [${list([...new Set(m.PRESET_TOOLS[p])])}]`).join(',\n')}
} as const satisfies Record<string, readonly string[]>

export type PresetName = keyof typeof PRESET_TOOLS
`
process.stdout.write(out)
