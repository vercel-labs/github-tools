import { afterEach, describe, expect, it, vi } from 'vitest'
import { fillGithubFooter, githubAppBot, githubAppBotIdentity, githubAppFooterValues, githubChannelFooterValues, githubFooterTokens, withGithubAppFooter } from './attribution'

function json(body: unknown, status = 200) {
  return new Response(JSON.stringify(body), { status, headers: { 'content-type': 'application/json' } })
}

function stubGithub(routes: Record<string, unknown>) {
  const requests: string[] = []
  vi.stubGlobal('fetch', vi.fn<typeof globalThis.fetch>(async (input, init) => {
    const url = new URL(String(input))
    const route = `${init?.method ?? 'GET'} ${decodeURIComponent(url.pathname)}`
    requests.push(route)
    return route in routes ? json(routes[route]) : json({ message: 'Not Found' }, 404)
  }))
  return requests
}

const bot = { slug: 'evlogai', name: 'Evi', login: 'evlogai[bot]', id: 313167257 }

afterEach(() => {
  vi.unstubAllGlobals()
})

describe('githubAppBot', () => {
  it('reads the App from the token\'s installations, then its bot account and display name', async () => {
    const requests = stubGithub({
      'GET /user/installations': { total_count: 1, installations: [{ id: 1, app_id: 2, app_slug: 'evlogai' }] },
      'GET /users/evlogai[bot]': { login: 'evlogai[bot]', id: 313167257, type: 'Bot' },
      'GET /apps/evlogai': { slug: 'evlogai', name: 'Evi' },
    })
    await expect(githubAppBot('ghu_test')).resolves.toEqual(bot)
    expect(requests.sort()).toEqual(['GET /apps/evlogai', 'GET /user/installations', 'GET /users/evlogai[bot]'])
  })

  it('names a private App by its slug, since GitHub hides it from user tokens', async () => {
    stubGithub({
      'GET /user/installations': { total_count: 1, installations: [{ id: 1, app_id: 2, app_slug: 'evlogai' }] },
      'GET /users/evlogai[bot]': { login: 'evlogai[bot]', id: 313167257, type: 'Bot' },
    })
    await expect(githubAppBot('ghu_test')).resolves.toEqual({ ...bot, name: 'evlogai' })
  })

  it('fails when GitHub lists no installation to the token', async () => {
    stubGithub({ 'GET /user/installations': { total_count: 0, installations: [] } })
    await expect(githubAppBot('ghu_test')).rejects.toMatchObject({ code: 'github_tools.APP_BOT_UNKNOWN' })
  })
})

describe('githubAppBotIdentity', () => {
  it('uses the noreply address GitHub links to the bot account', () => {
    expect(githubAppBotIdentity(bot)).toEqual({ name: 'evlogai[bot]', email: '313167257+evlogai[bot]@users.noreply.github.com' })
  })
})

describe('withGithubAppFooter', () => {
  it('closes the body with a line naming the App', () => {
    expect(withGithubAppFooter('Fixes the drain.\n', bot)).toBe('Fixes the drain.\n\n---\n\nGenerated by [Evi](https://github.com/apps/evlogai).')
  })

  it('uses the given footer instead of the default line', () => {
    expect(withGithubAppFooter('Fixes the drain.', bot, 'Opened by Evi.')).toBe('Fixes the drain.\n\n---\n\nOpened by Evi.')
  })

  it('shows the slug for a bot without a display name', () => {
    expect(withGithubAppFooter('Fixes the drain.', { slug: 'evlogai', login: 'evlogai[bot]', id: 313167257 })).toBe('Fixes the drain.\n\n---\n\nGenerated by [evlogai](https://github.com/apps/evlogai).')
  })

  it('is the whole body when there is none', () => {
    expect(withGithubAppFooter(undefined, bot)).toBe('Generated by [Evi](https://github.com/apps/evlogai).')
    expect(withGithubAppFooter('  ', bot)).toBe('Generated by [Evi](https://github.com/apps/evlogai).')
  })
})

describe('footer templates', () => {
  it('fills every token from the call', () => {
    const slack = { kind: 'channel:slack', metadata: { teamId: 'T1', channelId: 'C2', threadTs: '1700000000.000100', triggeringUserId: 'U3' } }
    const values = { ...githubAppFooterValues(bot), ...githubChannelFooterValues(slack), requester: '@HugoRCD' }
    expect(fillGithubFooter('Generated by {app} for {requester} from {origin}, in {channel} ({app.name}).', values))
      .toBe('Generated by [Evi](https://github.com/apps/evlogai) for @HugoRCD from a [Slack thread](https://app.slack.com/client/T1/C2/thread/C2-1700000000.000100), in Slack (Evi).')
  })

  it('lists the tokens a template uses, once each', () => {
    expect(githubFooterTokens('{app} for {requester}, {app} again, {agent}')).toEqual(['app', 'requester', 'agent'])
  })

  it('fails on a token with no value', () => {
    expect(() => fillGithubFooter('For {requester}.', githubAppFooterValues(bot))).toThrow('The footer token {requester} has no value for this call.')
  })
})

describe('githubChannelFooterValues', () => {
  it('recognizes Slack by its metadata, whatever the channel file is called', () => {
    expect(githubChannelFooterValues({ kind: 'channel:chat', metadata: { teamId: 'T1', channelId: 'C2', threadTs: '1.2', triggeringUserId: null } }))
      .toEqual({ channel: 'Slack', origin: 'a [Slack thread](https://app.slack.com/client/T1/C2/thread/C2-1.2)' })
  })

  it('names the Linear issue', () => {
    expect(githubChannelFooterValues({ kind: 'channel:linear', metadata: { agentSessionId: 's', commentId: null, issueId: 'i', issueIdentifier: 'EVL-815', organizationId: 'o' } }))
      .toEqual({ channel: 'Linear', origin: 'Linear issue EVL-815' })
  })

  it('falls back to the channel\'s name', () => {
    expect(githubChannelFooterValues({ kind: 'http', metadata: {} })).toEqual({ channel: 'the API', origin: 'the API' })
    expect(githubChannelFooterValues({ kind: 'channel:web', metadata: {} })).toEqual({ channel: 'web', origin: 'web' })
  })
})
