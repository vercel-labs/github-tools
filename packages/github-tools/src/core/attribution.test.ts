import { afterEach, describe, expect, it, vi } from 'vitest'
import { fillGithubFooter, githubAppBot, githubAppBotIdentity, githubAppFooterValues, githubFooterTokens, withGithubAppFooter } from './attribution'

function json(body: unknown, status = 200) {
  return new Response(JSON.stringify(body), { status, headers: { 'content-type': 'application/json' } })
}

function stubGithub(routes: Record<string, unknown>) {
  const requests: string[] = []
  vi.stubGlobal('fetch', vi.fn<typeof globalThis.fetch>(async (input, init) => {
    const url = new URL(String(input))
    const route = `${init?.method ?? 'GET'} ${decodeURIComponent(url.pathname)}`
    requests.push(route)
    return route in routes ? json(routes[route]) : json({ message: 'Not Found' }, 404)
  }))
  return requests
}

const bot = { slug: 'evlogai', login: 'evlogai[bot]', id: 313167257 }

afterEach(() => {
  vi.unstubAllGlobals()
})

describe('githubAppBot', () => {
  it('reads the App from the token\'s installations, then its bot account', async () => {
    const requests = stubGithub({
      'GET /user/installations': { total_count: 1, installations: [{ id: 1, app_id: 2, app_slug: 'evlogai' }] },
      'GET /users/evlogai[bot]': { login: 'evlogai[bot]', id: 313167257, type: 'Bot' },
    })
    await expect(githubAppBot('ghu_test')).resolves.toEqual(bot)
    expect(requests).toEqual(['GET /user/installations', 'GET /users/evlogai[bot]'])
  })

  it('fails when GitHub lists no installation to the token', async () => {
    stubGithub({ 'GET /user/installations': { total_count: 0, installations: [] } })
    await expect(githubAppBot('ghu_test')).rejects.toMatchObject({ code: 'github_tools.APP_BOT_UNKNOWN' })
  })
})

describe('githubAppBotIdentity', () => {
  it('uses the noreply address GitHub links to the bot account', () => {
    expect(githubAppBotIdentity(bot)).toEqual({ name: 'evlogai[bot]', email: '313167257+evlogai[bot]@users.noreply.github.com' })
  })
})

describe('withGithubAppFooter', () => {
  it('closes the body with a line naming the App', () => {
    expect(withGithubAppFooter('Fixes the drain.\n', bot)).toBe('Fixes the drain.\n\n---\n\nGenerated by [evlogai](https://github.com/apps/evlogai).')
  })

  it('uses the given footer instead of the default line', () => {
    expect(withGithubAppFooter('Fixes the drain.', bot, 'Opened by Evi.')).toBe('Fixes the drain.\n\n---\n\nOpened by Evi.')
  })

  it('is the whole body when there is none', () => {
    expect(withGithubAppFooter(undefined, bot)).toBe('Generated by [evlogai](https://github.com/apps/evlogai).')
    expect(withGithubAppFooter('  ', bot)).toBe('Generated by [evlogai](https://github.com/apps/evlogai).')
  })
})

describe('footer templates', () => {
  it('fills every token from the call', () => {
    const values = { ...githubAppFooterValues(bot), requester: '@HugoRCD', channel: 'slack' }
    expect(fillGithubFooter('Opened by Evi in {channel} for {requester}, through {app} ({app.name}).', values))
      .toBe('Opened by Evi in slack for @HugoRCD, through [evlogai](https://github.com/apps/evlogai) (evlogai).')
  })

  it('lists the tokens a template uses, once each', () => {
    expect(githubFooterTokens('{app} for {requester}, {app} again, {agent}')).toEqual(['app', 'requester', 'agent'])
  })

  it('fails on a token with no value', () => {
    expect(() => fillGithubFooter('For {requester}.', githubAppFooterValues(bot))).toThrow('The footer token {requester} has no value for this call.')
  })
})
