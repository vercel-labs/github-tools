import { createOctokit } from '../client'
import type { CommitIdentity } from '../types'
import { EvlogError, githubToolsErrors } from './errors'
import type { GithubToolName } from './tool-names'

/** A GitHub App's bot account, the identity GitHub shows for what the App writes. */
export type GithubAppBot = {
  /** The App's slug, as in `https://github.com/apps/<slug>`. */
  slug: string
  /** The App's display name, as its page on GitHub shows it. */
  name: string
  /** The bot's login, `<slug>[bot]`. */
  login: string
  /** The bot's numeric user id. */
  id: number
}

/** The tools that create a commit and add `coAuthors` to its message. */
export const GITHUB_COMMIT_TOOLS: ReadonlySet<GithubToolName> = new Set([
  'createOrUpdateFile',
  'editFiles',
  'mergePullRequest',
  'enablePullRequestAutoMerge',
])

/**
 * Read the bot of the GitHub App that issued `token`, a user access token. GitHub lists only that
 * App's installations to such a token, so the first one names the App.
 */
export async function githubAppBot(token: string): Promise<GithubAppBot> {
  const octokit = createOctokit(token)
  const { data } = await octokit.rest.apps.listInstallationsForAuthenticatedUser({ per_page: 1 })
  const slug = data.installations[0]?.app_slug
  if (!slug) throw githubToolsErrors.APP_BOT_UNKNOWN()
  const [{ data: bot }, name] = await Promise.all([
    octokit.rest.users.getByUsername({ username: `${slug}[bot]` }),
    octokit.rest.apps.getBySlug({ app_slug: slug }).then(
      ({ data }) => data?.name ?? slug,
      // GitHub hides a private App from user tokens, so its slug is the only name to show.
      (error: unknown) => {
        if (EvlogError.isEvlogError(error) && error.status === 404) return slug
        throw error
      },
    ),
  ])
  return { slug, name, login: bot.login, id: bot.id }
}

/** The bot as a commit identity, with the noreply address GitHub links to its account. */
export function githubAppBotIdentity(bot: GithubAppBot): CommitIdentity {
  return { name: bot.login, email: `${bot.id}+${bot.login}@users.noreply.github.com` }
}

/**
 * The tokens a footer template can use, each filled from the call:
 *
 * - `{app}`: the App as a Markdown link, `[<name>](https://github.com/apps/<slug>)`
 * - `{app.name}`: the App's display name
 * - `{requester}`: the person whose token runs the call, as `@<login>`
 * - `{channel}`: the name of the channel the request came from, such as `Slack` or `Linear`
 * - `{origin}`: where the request came from, as precisely as the channel tells: a link to the Slack
 *   thread, the Linear issue, or else the channel's name
 */
export const GITHUB_FOOTER_TOKENS = ['app', 'app.name', 'requester', 'channel', 'origin'] as const

/** A token of {@link GITHUB_FOOTER_TOKENS}. */
export type GithubFooterToken = typeof GITHUB_FOOTER_TOKENS[number]

const TOKEN = /\{([a-z.]+)\}/g

/** The default footer template. */
export const DEFAULT_GITHUB_FOOTER = 'Generated by {app} for {requester} from {origin}.'

/** The channel serving a call, as eve's `ctx.channel` gives it. */
export type GithubFooterChannel = {
  /** `channel:<file name>` for an authored channel, or `http`, `schedule`, `subagent`, `unknown`. */
  kind: string
  /** What the channel's `metadata(state)` hook returns. */
  metadata: Readonly<Record<string, unknown>>
}

const CHANNEL_NAMES: Record<string, string> = {
  slack: 'Slack',
  github: 'GitHub',
  linear: 'Linear',
  teams: 'Microsoft Teams',
  discord: 'Discord',
  telegram: 'Telegram',
  http: 'the API',
}

const isString = (value: unknown): value is string => typeof value === 'string' && value !== ''

function slackThread({ teamId, channelId, threadTs }: Readonly<Record<string, unknown>>) {
  return isString(teamId) && isString(channelId) && isString(threadTs) ? { teamId, channelId, threadTs } : undefined
}

// A channel's kind comes from its file name, so Slack and Linear are recognized by their metadata.
function channelName({ kind, metadata }: GithubFooterChannel): string {
  if ('threadTs' in metadata && 'channelId' in metadata) return 'Slack'
  if ('agentSessionId' in metadata) return 'Linear'
  const name = kind.replace(/^channel:/, '')
  return CHANNEL_NAMES[name] ?? name
}

function origin(channel: GithubFooterChannel): string {
  const thread = slackThread(channel.metadata)
  if (thread) return `a [Slack thread](https://app.slack.com/client/${thread.teamId}/${thread.channelId}/thread/${thread.channelId}-${thread.threadTs})`
  const { issueIdentifier } = channel.metadata
  if (isString(issueIdentifier)) return `Linear issue ${issueIdentifier}`
  return channelName(channel)
}

/** The tokens `template` uses, in order and without repeats, including ones that aren't in {@link GITHUB_FOOTER_TOKENS}. */
export function githubFooterTokens(template: string): string[] {
  return [...new Set([...template.matchAll(TOKEN)].map(match => match[1]!))]
}

/** `template` with every token replaced by its value. A token without a value fails, so a typo never reaches a pull request. */
export function fillGithubFooter(template: string, values: Partial<Record<GithubFooterToken, string>>): string {
  return template.replace(TOKEN, (token, name: string) => {
    const value = values[name as GithubFooterToken]
    if (value === undefined) throw new Error(`The footer token ${token} has no value for this call.`)
    return value
  })
}

/** The App's own footer values, which every call can fill. */
export function githubAppFooterValues(bot: GithubAppBot): Pick<Record<GithubFooterToken, string>, 'app' | 'app.name'> {
  return { 'app': `[${bot.name}](https://github.com/apps/${bot.slug})`, 'app.name': bot.name }
}

/** The footer values the channel serving a call fills: `{channel}` and `{origin}`. */
export function githubChannelFooterValues(channel: GithubFooterChannel): Pick<Record<GithubFooterToken, string>, 'channel' | 'origin'> {
  return { channel: channelName(channel), origin: origin(channel) }
}

/** The login of the person `token` belongs to. */
export async function githubLogin(token: string): Promise<string> {
  const { data } = await createOctokit(token).rest.users.getAuthenticated()
  return data.login
}

/**
 * `body` with a closing line crediting the App: `footer` when given, otherwise
 * `Generated by [<name>](https://github.com/apps/<slug>).`
 */
export function withGithubAppFooter(body: string | undefined, bot: GithubAppBot, footer = fillGithubFooter('Generated by {app}.', githubAppFooterValues(bot))): string {
  return body?.trim() ? `${body.trimEnd()}\n\n---\n\n${footer}` : footer
}
