import { createOctokit } from '../client'
import type { CommitIdentity } from '../types'
import { githubToolsErrors } from './errors'
import type { GithubToolName } from './tool-names'

/** A GitHub App's bot account, the identity GitHub shows for what the App writes. */
export type GithubAppBot = {
  /** The App's slug, as in `https://github.com/apps/<slug>`. */
  slug: string
  /** The bot's login, `<slug>[bot]`. */
  login: string
  /** The bot's numeric user id. */
  id: number
}

/** The tools that create a commit and add `coAuthors` to its message. */
export const GITHUB_COMMIT_TOOLS: ReadonlySet<GithubToolName> = new Set([
  'createOrUpdateFile',
  'editFiles',
  'mergePullRequest',
  'enablePullRequestAutoMerge',
])

/**
 * Read the bot of the GitHub App that issued `token`, a user access token. GitHub lists only that
 * App's installations to such a token, so the first one names the App.
 */
export async function githubAppBot(token: string): Promise<GithubAppBot> {
  const octokit = createOctokit(token)
  const { data } = await octokit.rest.apps.listInstallationsForAuthenticatedUser({ per_page: 1 })
  const slug = data.installations[0]?.app_slug
  if (!slug) throw githubToolsErrors.APP_BOT_UNKNOWN()
  const { data: bot } = await octokit.rest.users.getByUsername({ username: `${slug}[bot]` })
  return { slug, login: bot.login, id: bot.id }
}

/** The bot as a commit identity, with the noreply address GitHub links to its account. */
export function githubAppBotIdentity(bot: GithubAppBot): CommitIdentity {
  return { name: bot.login, email: `${bot.id}+${bot.login}@users.noreply.github.com` }
}

/**
 * The tokens a footer template can use, each filled from the call:
 *
 * - `{app}`: the App as a Markdown link, `[<slug>](https://github.com/apps/<slug>)`
 * - `{app.name}`: the App's slug
 * - `{requester}`: the person whose token runs the call, as `@<login>`
 * - `{channel}`: where the request came from, such as `slack`, `github` or `http`
 */
export const GITHUB_FOOTER_TOKENS = ['app', 'app.name', 'requester', 'channel'] as const

/** A token of {@link GITHUB_FOOTER_TOKENS}. */
export type GithubFooterToken = typeof GITHUB_FOOTER_TOKENS[number]

const TOKEN = /\{([a-z.]+)\}/g

/** The default footer template. */
export const DEFAULT_GITHUB_FOOTER = 'Generated by {app}.'

/** The tokens `template` uses, in order and without repeats, including ones that aren't in {@link GITHUB_FOOTER_TOKENS}. */
export function githubFooterTokens(template: string): string[] {
  return [...new Set([...template.matchAll(TOKEN)].map(match => match[1]!))]
}

/** `template` with every token replaced by its value. A token without a value fails, so a typo never reaches a pull request. */
export function fillGithubFooter(template: string, values: Partial<Record<GithubFooterToken, string>>): string {
  return template.replace(TOKEN, (token, name: string) => {
    const value = values[name as GithubFooterToken]
    if (value === undefined) throw new Error(`The footer token ${token} has no value for this call.`)
    return value
  })
}

/** The App's own footer values, which every call can fill. */
export function githubAppFooterValues(bot: GithubAppBot): Pick<Record<GithubFooterToken, string>, 'app' | 'app.name'> {
  return { 'app': `[${bot.slug}](https://github.com/apps/${bot.slug})`, 'app.name': bot.slug }
}

/** The login of the person `token` belongs to. */
export async function githubLogin(token: string): Promise<string> {
  const { data } = await createOctokit(token).rest.users.getAuthenticated()
  return data.login
}

/**
 * `body` with a closing line crediting the App: `footer` when given, otherwise
 * `Generated by [<app>](https://github.com/apps/<app>).`
 */
export function withGithubAppFooter(body: string | undefined, bot: GithubAppBot, footer = fillGithubFooter(DEFAULT_GITHUB_FOOTER, githubAppFooterValues(bot))): string {
  return body?.trim() ? `${body.trimEnd()}\n\n---\n\n${footer}` : footer
}
